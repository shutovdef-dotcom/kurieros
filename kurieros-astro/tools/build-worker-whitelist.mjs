#!/usr/bin/env node
// Reads src/data/ozon-vacancies.json and emits a compact ES module
// (workers/ozon-lead/src/whitelist.js) containing two exports:
//
//   ALLOWED_TUPLES       — Set<`${slug}|${cityID}|${hireObjectUUID}`>
//   ALLOWED_VACANCIES    — Set<slug>
//
// The Worker uses these for defence-in-depth: the kurerok.ru bundle
// already carries the same tuples per vacancy page, but the Worker
// rejects anything that isn't in the whitelist so a malicious POST
// from another origin can't pivot the proxy to arbitrary Ozon HR
// pipelines (e.g. "директор" or "региональный менеджер").

import fs from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const dataPath = path.join(__dirname, '..', 'src', 'data', 'ozon-vacancies.json');
const outPath = path.join(__dirname, '..', 'workers', 'ozon-lead', 'src', 'whitelist.js');

const data = JSON.parse(await fs.readFile(dataPath, 'utf8'));

const tuples = [];
const slugs = new Set();
for (const v of data) {
  slugs.add(v.slug);
  for (const c of v.cities) {
    for (const h of c.hireObjects) {
      tuples.push(`${v.slug}|${c.cityID}|${h.uuid}`);
    }
  }
}
tuples.sort();

const banner = `// AUTO-GENERATED by tools/build-worker-whitelist.mjs from
// src/data/ozon-vacancies.json. Do NOT edit by hand — re-run
// \`node tools/build-worker-whitelist.mjs\` (or the wrapper
// \`workers/ozon-lead/scripts/refresh-whitelist.sh\`) after the form's
// vacancy/city catalogue changes upstream.`;

const body = `${banner}

// ${tuples.length} (vacancy, city, hireObject) tuples covering ${slugs.size} backend slugs.
export const ALLOWED_TUPLES = new Set([
${tuples.map((t) => `  ${JSON.stringify(t)},`).join('\n')}
]);

export const ALLOWED_VACANCIES = new Set([
${[...slugs].sort().map((s) => `  ${JSON.stringify(s)},`).join('\n')}
]);
`;

await fs.writeFile(outPath, body, 'utf8');
console.error(`Wrote ${outPath} (${tuples.length} tuples, ${slugs.size} slugs).`);
