#!/usr/bin/env node
// Reads BOTH src/data/ozon-vacancies.json (ref-courier-sklad,
// combineCustomerVacancy schema) and src/data/ozon-fresh-vacancies.json
// (fresh-referral-office, customer/vacancy schema) and emits a compact
// ES module (workers/ozon-lead/src/whitelist.js) with two exports:
//
//   ALLOWED_TUPLES       — Set<`${slug}|${cityID}|${hireObjectUUID}`>
//   ALLOWED_VACANCIES    — Set<slug>
//
// where for sklad entries the slug is the raw `combineCustomerVacancy`
// (`rocket:courier`, `ff:operator`, …) and for Fresh entries the slug
// is `${customer}:${vacancy}` (e.g. `express:courier`,
// `express:adminPersonal`). The Worker discriminates on
// `customer === 'express'` to pick the matching upstream payload
// shape. Both pipelines share the same defence-in-depth check —
// requests with an unknown tuple are rejected with 400.

import fs from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const skladPath = path.join(__dirname, '..', 'src', 'data', 'ozon-vacancies.json');
const freshPath = path.join(__dirname, '..', 'src', 'data', 'ozon-fresh-vacancies.json');
const outPath = path.join(__dirname, '..', 'workers', 'ozon-lead', 'src', 'whitelist.js');

const skladData = JSON.parse(await fs.readFile(skladPath, 'utf8'));
const freshData = JSON.parse(await fs.readFile(freshPath, 'utf8').catch(() => '[]'));

const tuples = [];
const slugs = new Set();

// ref-courier-sklad: raw combineCustomerVacancy slug (e.g. `rocket:courier`).
for (const v of skladData) {
  slugs.add(v.slug);
  for (const c of v.cities) {
    for (const h of c.hireObjects) {
      tuples.push(`${v.slug}|${c.cityID}|${h.uuid}`);
    }
  }
}

// fresh-referral-office: composite slug `${customer}:${vacancy}`
// (e.g. `express:courier`). Worker re-splits on `:` to send the
// correct upstream payload.
for (const v of freshData) {
  const slug = `${v.customer}:${v.vacancy}`;
  slugs.add(slug);
  for (const c of v.cities) {
    for (const h of c.hireObjects) {
      tuples.push(`${slug}|${c.cityID}|${h.uuid}`);
    }
  }
}

tuples.sort();

const banner = `// AUTO-GENERATED by tools/build-worker-whitelist.mjs from
// src/data/ozon-vacancies.json (ref-courier-sklad, combineCustomerVacancy
// schema) and src/data/ozon-fresh-vacancies.json (fresh-referral-office,
// customer/vacancy schema). Do NOT edit by hand — re-run
// \`node tools/build-worker-whitelist.mjs\` after either catalogue
// changes upstream.`;

const body = `${banner}

// ${tuples.length} (vacancy, city, hireObject) tuples covering ${slugs.size} backend slugs.
export const ALLOWED_TUPLES = new Set([
${tuples.map((t) => `  ${JSON.stringify(t)},`).join('\n')}
]);

export const ALLOWED_VACANCIES = new Set([
${[...slugs].sort().map((s) => `  ${JSON.stringify(s)},`).join('\n')}
]);
`;

await fs.writeFile(outPath, body, 'utf8');
console.error(`Wrote ${outPath} (${tuples.length} tuples, ${slugs.size} slugs).`);
